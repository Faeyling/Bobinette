/** Hauteur approximative du bas de jupe sur la silhouette, pour l'illustration. */
function lengthToY(a) {
  const L = +a.longueur || 58;
  const waist = BODY_Y[a.port] ?? BODY_Y.naturelle;
  // échelle : environ 2,8 unités SVG par cm pour une silhouette de 1,65 m
  return Math.min(BODY_Y.cheville + 6, waist + L * 2.75);
}

